#!/usr/bin/env python3
"""Export the separate overlap run, without altering quota/LLVM values."""
import json
from pathlib import Path
import runpy

ROOT = Path(__file__).resolve().parents[1]


def export():
    driver = runpy.run_path(str(ROOT / "scripts/run_overlap_comparison.py"))
    output = ROOT / "results/current/overlap"
    saved = json.loads((output / "summary.json").read_text(encoding="utf-8"))
    derived = driver["summarize"](output)
    if any(derived[k] != saved[k] for k in derived):
        raise ValueError("overlap raw/summary mismatch")
    if saved["source_versions_sha256"] != driver["version_hashes"]():
        raise ValueError("overlap result source version mismatch; rerun in a new directory")
    if driver["scientific_failures"](saved):
        raise ValueError("overlap scientific failure gates")
    c = saved["counts"]
    values = {"Programs": c["programs"], "Bindings": c["bindings"],
              "Candidates": c["candidates"], "Conflicts": c["conflict_pairs"],
              "Discarded": saved["policies"]["mode4"]["discarded_candidates"],
              "Embeddings": c["embeddings"], "Executions": c["full_comparisons"],
              "Mutations": c["mutations"], "CapacityRejections": c["capacity_rejections"]}
    paper = ROOT.parent / "paper"
    if not paper.is_dir():
        raise ValueError("overlap paper export needs sibling paper tree")
    macros = ["% Generated by artifact/scripts/export_overlap_data.py from results/current/overlap."]
    macros.extend(r"\newcommand{\TMOverlap" + k + "}{" + str(v) + "}" for k, v in values.items())
    (paper / "overlap-data.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    labels = {"mode4": "Mode 4", "source-first": "Source-first",
              "singleton-first": "Singleton-first", "adjacent-only": "Adjacent-only"}
    table = [r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
             r"Policy & Sites & User bits & Optimum & 8-bit success\\", r"\midrule"]
    for p in driver["overlap"].POLICIES:
        b = saved["policies"][p]
        table.append(f"{labels[p]} & {b['selected_sites']:,} & {b['user_capacity_bits']:,} & "
                     f"{b['optimal_programs']}/192 & {b['fixed8_embeddings']}/192 " + r"\\")
    table.extend([r"\bottomrule", r"\end{tabular}"])
    (paper / "tables/overlap-comparison.tex").write_text("\n".join(table) + "\n", encoding="utf-8")
    print("Exported overlap table and", len(values), "measured macros")


if __name__ == "__main__":
    export()
